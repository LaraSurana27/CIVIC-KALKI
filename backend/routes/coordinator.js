/**
 * CIVIC-KALKI — Coordinator AI Routes (Ayush's Module)
 *
 * POST /coordinator/:id/analyze
 *   - Restricted to: coordinator_area, coordinator_general, director, admin
 *   - For coordinator_area: entity must belong to their assignedArea (or be unassigned)
 *   - Generates advisory coordinator analysis via Groq
 *   - NEVER changes workflow state, status, or permissions
 *
 * GET /coordinator/legal-corpus
 *   - Restricted to: coordinator_area, coordinator_general, director, admin
 *   - Returns metadata about the legal/constitutional corpus (sources, sections)
 */

'use strict';

const express = require('express');
const router = express.Router();
const { verifyToken, checkRole } = require('../middleware/auth');
const { generateCoordinatorAnalysis } = require('../services/coordinatorAI');
const { getCorpusMetadata } = require('../services/legalRag');
const prisma = require('../db');

function createError(message, statusCode) {
  const err = new Error(message);
  err.statusCode = statusCode;
  return err;
}

function parsePositiveInt(value, fieldName) {
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw createError(
      `"${fieldName}" must be a positive integer. Received: ${value}`,
      400
    );
  }
  return parsed;
}

// ─────────────────────────────────────────────────────────────────────────────
// POST /coordinator/:id/analyze
// ─────────────────────────────────────────────────────────────────────────────
router.post(
  '/:id/analyze',
  verifyToken,
  checkRole(['coordinator_area', 'coordinator_general', 'director', 'admin']),
  async (req, res, next) => {
    try {
      const entityId = parsePositiveInt(req.params.id, 'id');

      // Verify entity exists
      const entity = await prisma.entity.findUnique({
        where: { entity_id: entityId },
        select: {
          entity_id: true,
          area: true,
          status: true,
          entity_type_id: true,
        },
      });

      if (!entity) {
        return next(createError(`Entity with id ${entityId} was not found.`, 404));
      }

      // Cannot analyze deleted entities
      if (entity.status === 'deleted') {
        return next(createError('Deleted entities cannot be analyzed.', 400));
      }

      // Area-based access restriction for coordinator_area
      // coordinator_area can only analyze entities in their assigned area.
      if (req.user.role === 'coordinator_area') {
        const userArea = req.user.assignedArea || req.user.assigned_area;
        const entityArea = entity.area;

        if (userArea && entityArea && String(userArea).trim() !== String(entityArea).trim()) {
          return next(createError(
            `You are assigned to area "${userArea}" and cannot analyze cases in area "${entityArea}".`,
            403
          ));
        }
      }

      const result = await generateCoordinatorAnalysis(entityId, req.user);

      return res.status(200).json({
        success: true,
        data: result.report,
        log_id: result.logId,
        similar_cases: result.similarCases,
        legal_context_meta: result.legalContext,
        advisory_disclaimer:
          'This analysis is generated by AI and is ADVISORY ONLY. ' +
          'An authorized human officer must review all findings and make all official decisions. ' +
          'AI analysis does not constitute approval, rejection, or any workflow action.',
      });
    } catch (err) {
      return next(err);
    }
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// GET /coordinator/legal-corpus
// Returns metadata about the legal RAG corpus (for transparency and reference)
// ─────────────────────────────────────────────────────────────────────────────
router.get(
  '/legal-corpus',
  verifyToken,
  checkRole(['coordinator_area', 'coordinator_general', 'director', 'admin']),
  (req, res) => {
    const corpus = getCorpusMetadata();
    return res.status(200).json({
      success: true,
      data: corpus,
      disclaimer:
        'These passages are reproduced from verified official government sources for advisory reference. ' +
        'They are not legal advice. Verify current versions from official sources before relying on any passage. ' +
        'Official source: https://www.legislative.gov.in/documents',
    });
  }
);

module.exports = router;
