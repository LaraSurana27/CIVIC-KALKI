function attachHomeEvents() {

  // ── Header scroll effect ──
  const header = document.getElementById('ck-home-header');
  if (header) {
    window.addEventListener('scroll', () => {
      header.classList.toggle('scrolled', window.scrollY > 40);
    }, { passive: true });
  }

  // ── Mobile burger ──
  const burger = document.getElementById('ck-home-burger');
  const nav = document.getElementById('ck-home-nav');
  if (burger && nav) {
    burger.addEventListener('click', () => {
      nav.classList.toggle('open');
      burger.classList.toggle('open');
    });
  }

  // ── Feature Tabs ──
  const tabContainer = document.getElementById('ck-feature-tabs');
  if (tabContainer) {
    tabContainer.addEventListener('click', e => {
      const btn = e.target.closest('.ck-tab-btn');
      if (!btn) return;
      const tabId = btn.dataset.tab;

      tabContainer.querySelectorAll('.ck-tab-btn').forEach(b => b.classList.remove('active'));
      tabContainer.querySelectorAll('.ck-tab-panel').forEach(p => p.classList.remove('active'));
      btn.classList.add('active');
      const panel = document.getElementById(tabId);
      if (panel) panel.classList.add('active');
    });
  }

  // ── FAQ Accordion ──
  const faqList = document.getElementById('ck-faq-list');
  if (faqList) {
    faqList.addEventListener('click', e => {
      const btn = e.target.closest('.ck-faq-q');
      if (!btn) return;
      const item = btn.closest('.ck-faq-item');
      const wasOpen = item.classList.contains('open');
      // close all
      faqList.querySelectorAll('.ck-faq-item').forEach(i => i.classList.remove('open'));
      if (!wasOpen) item.classList.add('open');
    });
  }

  // ── Mascot eye tracking ──
  const pupilL = document.getElementById('ck-pupil-l');
  const pupilR = document.getElementById('ck-pupil-r');
  if (pupilL && pupilR) {
    document.addEventListener('mousemove', e => {
      const movePupil = (pupil) => {
        const eye = pupil.parentElement;
        const rect = eye.getBoundingClientRect();
        const cx = rect.left + rect.width / 2;
        const cy = rect.top + rect.height / 2;
        const dx = e.clientX - cx;
        const dy = e.clientY - cy;
        const angle = Math.atan2(dy, dx);
        const maxDist = rect.width * 0.22;
        const dist = Math.min(Math.sqrt(dx*dx + dy*dy) * 0.15, maxDist);
        pupil.style.transform = `translate(${Math.cos(angle) * dist}px, ${Math.sin(angle) * dist}px)`;
      };
      movePupil(pupilL);
      movePupil(pupilR);
    }, { passive: true });
  }

  // ── Smooth scroll for anchor links ──
  document.querySelectorAll('.ck-home a[href^="#"]').forEach(link => {
    link.addEventListener('click', e => {
      e.preventDefault();
      const target = document.querySelector(link.getAttribute('href'));
      if (target) {
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
        // close mobile nav
        const nav = document.getElementById('ck-home-nav');
        const burger = document.getElementById('ck-home-burger');
        if (nav) nav.classList.remove('open');
        if (burger) burger.classList.remove('open');
      }
    });
  });

  // ── Intersection Observer for scroll animations ──
  const observerCallback = (entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('ck-visible');
      }
    });
  };
  const observer = new IntersectionObserver(observerCallback, { threshold: 0.1, rootMargin: '0px 0px -60px 0px' });
  document.querySelectorAll('.ck-how-card, .ck-buzz-meme, .ck-about-text, .ck-about-visual, .ck-faq-item').forEach(el => {
    observer.observe(el);
  });
}
